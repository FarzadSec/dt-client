class Strings(val language: String) {
    private val table = if (language == "en") en else fa

    operator fun invoke(key: String, vararg vars: Pair<String, Any>): String {
        var text = table[key] ?: en[key] ?: key
        for ((k, v) in vars) text = text.replace("{$k}", v.toString())
        return text
    }

    fun error(code: String): String = invoke(if (table.containsKey("error.$code")) "error.$code" else "error.unexpected")
}
