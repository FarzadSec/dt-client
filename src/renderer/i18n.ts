const dictionaries: Record<Language, Record<Key, string>> = { en, fa };

export type Translate = (key: Key | string, vars?: Record<string, string | number>) => string;

export function translator(lang: Language): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let text = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) text = text.replace(`{${name}}`, String(value));
    return text;
  };
}

export function errorText(t: Translate, code: string): string {
  const key = `error.${code}`;
  return t(key) === key ? t('error.unexpected') : t(key);
}
